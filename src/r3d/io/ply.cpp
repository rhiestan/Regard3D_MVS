PointCloud read_ply(const std::filesystem::path& path) {
  const std::string name = path_string(path);
  const std::vector<std::uint8_t> data = read_file(path);
  const PlyHeader header = parse_header(data, name);
  BodyReader reader(data, header.body_offset, header.encoding, name);

  PointCloud cloud;
  bool vertex_seen = false;
  for (const PlyElementDef& element : header.elements) {
    const bool is_vertex = element.name == "vertex" && !vertex_seen;
    if (!is_vertex) {
      // Skip the element; list lengths require reading the counts.
      for (std::size_t i = 0; i < element.count; ++i) {
        for (const PlyPropertyDef& prop : element.properties) {
          const std::size_t values = prop.is_list ? static_cast<std::size_t>(reader.read(prop.count_type)) : 1;
          for (std::size_t k = 0; k < values; ++k) reader.read(prop.type);
        }
      }
      continue;
    }
    vertex_seen = true;

    // Role of each property: 0-2 position, 3-5 normal, 6-8 color, 9 view_ids,
    // 10 scalar attribute, 11 ignored.
    enum Role { px, py, pz, nx, ny, nz, cr, cg, cb, views, scalar, ignore };
    std::vector<Role> roles;
    std::vector<std::size_t> scalar_slot(element.properties.size(), 0);
    bool has_pos = false, has_normal = false, has_color = false, has_views = false, double_pos = false;
    std::vector<std::string> scalar_names;
    for (std::size_t p = 0; p < element.properties.size(); ++p) {
      const PlyPropertyDef& prop = element.properties[p];
      const std::string& n = prop.name;
      Role role = ignore;
      if (prop.is_list) {
        role = n == "view_ids" ? views : ignore;
      } else if (n == "x") role = px;
      else if (n == "y") role = py;
      else if (n == "z") role = pz;
      else if (n == "nx") role = nx;
      else if (n == "ny") role = ny;
      else if (n == "nz") role = nz;
      else if (n == "red" || n == "r" || n == "diffuse_red") role = cr;
      else if (n == "green" || n == "g" || n == "diffuse_green") role = cg;
      else if (n == "blue" || n == "b" || n == "diffuse_blue") role = cb;
      else if (n == "alpha" || n == "a") role = ignore;
      else {
        role = scalar;
        scalar_slot[p] = scalar_names.size();
        scalar_names.push_back(n);
      }
      has_pos |= role == px;
      has_normal |= role == nx;
      has_color |= role == cr;
      has_views |= role == views;
      double_pos |= role == px && prop.type == PlyType::float64;
      roles.push_back(role);
    }
    if (!has_pos) throw_io_error("'{}': PLY vertex element without x/y/z", name);

    const std::size_t n = element.count;
    cloud.positions.resize(n);
    if (has_normal) cloud.normals.resize(n, Eigen::Vector3f::Zero());
    if (has_color) cloud.colors.resize(n, {0, 0, 0});
    if (has_views) cloud.visibility.resize(n);
    for (const std::string& s : scalar_names) cloud.scalars.emplace_back(s, std::vector<float>(n, 0.0f));

    // With an r3d_origin comment the stored coordinates are already relative
    // to it; otherwise they are absolute and get shifted into the origin frame.
    const bool relative_in_file = header.origin.has_value();
    bool origin_set = relative_in_file;
    if (relative_in_file) cloud.origin = *header.origin;
    for (std::size_t i = 0; i < n; ++i) {
      Eigen::Vector3d pos = Eigen::Vector3d::Zero();
      for (std::size_t p = 0; p < element.properties.size(); ++p) {
        const PlyPropertyDef& prop = element.properties[p];
        if (prop.is_list) {
          const auto count = static_cast<std::size_t>(reader.read(prop.count_type));
          if (roles[p] == views) {
            auto& ids = cloud.visibility[i];
            ids.resize(count);
            for (std::size_t k = 0; k < count; ++k) ids[k] = static_cast<std::uint32_t>(reader.read(prop.type));
          } else {
            for (std::size_t k = 0; k < count; ++k) reader.read(prop.type);
          }
          continue;
        }
        const double v = reader.read(prop.type);
        switch (roles[p]) {
          case px: pos.x() = v; break;
          case py: pos.y() = v; break;
          case pz: pos.z() = v; break;
          case nx: cloud.normals[i].x() = static_cast<float>(v); break;
          case ny: cloud.normals[i].y() = static_cast<float>(v); break;
          case nz: cloud.normals[i].z() = static_cast<float>(v); break;
          case cr: cloud.colors[i][0] = to_color(v, prop.type); break;
          case cg: cloud.colors[i][1] = to_color(v, prop.type); break;
          case cb: cloud.colors[i][2] = to_color(v, prop.type); break;
          case scalar: cloud.scalars[scalar_slot[p]].second[i] = static_cast<float>(v); break;
          case views:
          case ignore: break;
        }
      }
      if (!origin_set && double_pos) {
        cloud.origin = Eigen::Vector3d(std::round(pos.x()), std::round(pos.y()), std::round(pos.z()));
        origin_set = true;
      }
      cloud.positions[i] = (relative_in_file ? pos : Eigen::Vector3d(pos - cloud.origin)).cast<float>();
    }
  }
  if (!vertex_seen) throw_io_error("'{}': PLY file without vertex element", name);
  return cloud;
}

